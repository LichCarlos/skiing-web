export const sloganPixels: readonly (readonly string[])[] = phrases.map(
  (rows) => [
    rows
      .flatMap((row, y) =>
        Array.from(row, (cell, x) =>
          cell === "#" ? `M${x + 3},${y + 6}h0.92v0.92h-0.92z` : "",
        ),
      )
      .join(""),
  ],
);
